<?php

namespace App\Services;

use App\Models\Invoice;
use App\Models\Payment;

/** Generates simple downloadable statements without an external PDF service. */
class BillingDocumentPdf
{
    public function invoice(Invoice $invoice): string
    {
        $lease = $invoice->lease;
        $room = $lease?->room;
        $lines = [
            'BOARDEASE RENTAL INVOICE',
            'Invoice number: INV-'.str_pad((string) $invoice->id, 6, '0', STR_PAD_LEFT),
            'Billing period: '.$invoice->billing_period,
            'Tenant: '.($lease?->tenant?->name ?? 'Tenant'),
            'Tenant email: '.($lease?->tenant?->email ?? 'Not provided'),
            'Tenant phone: '.($lease?->tenant?->phone ?? 'Not provided'),
            'Landlord: '.($lease?->landlord?->name ?? 'Landlord'),
            'Landlord email: '.($lease?->landlord?->email ?? 'Not provided'),
            'Landlord phone: '.($lease?->landlord?->phone ?? 'Not provided'),
            'Room: '.($room?->room_number ?? '—').' - '.($room?->title ?? 'Rental room'),
            'Property / location: '.($room?->location ?? 'Not provided'),
            'Due date: '.$invoice->due_date?->toDateString(),
            'Payment status: '.strtoupper((string) $invoice->status),
            '',
            'RENT AND ADDITIONAL CHARGES',
            'Base rent: PHP '.number_format((float) $invoice->base_rent, 2),
            'Additional charge itemization (included in the subtotal below):',
        ];
        if ($invoice->charges->isEmpty()) {
            $lines[] = 'No additional charges.';
        }
        foreach ($invoice->charges as $charge) {
            $category = $charge->utility_type
                ? 'Utility - '.ucfirst($charge->utility_type)
                : 'Category - '.str_replace('_', ' ', (string) $charge->category);
            $lines[] = $category.' | '.($charge->description ?: 'Additional charge')
                .' | Period: '.($charge->billing_period ?: $invoice->billing_period)
                .' | PHP '.number_format((float) $charge->amount, 2);
        }
        $lines[] = 'Additional charges subtotal: PHP '.number_format((float) $invoice->additional_charges_total, 2);
        $lines[] = 'Invoice total - base rent plus additional charges: PHP '.number_format((float) $invoice->total_amount_due, 2);
        $lines[] = 'Amount paid: PHP '.number_format((float) $invoice->amount_paid, 2);
        $lines[] = 'Remaining balance: PHP '.number_format((float) $invoice->remainingBalance(), 2);
        $lines[] = 'Invoice status: '.strtoupper((string) $invoice->status);
        $lines[] = '';
        $lines[] = 'PAYMENT HISTORY';
        if ($invoice->payments->isEmpty()) {
            $lines[] = 'No payments recorded.';
        } else {
            foreach ($invoice->payments as $payment) {
                $lines[] = sprintf(
                    '%s | %s | PHP %s | %s | %s',
                    $payment->paid_at?->toDateTimeString() ?? $payment->created_at?->toDateTimeString() ?? 'Date not recorded',
                    strtoupper((string) ($payment->transaction_status ?? 'succeeded')),
                    number_format((float) $payment->amount, 2),
                    $payment->method,
                    $payment->reference_number ?: 'No reference',
                );
            }
        }
        $lines[] = '';
        $lines[] = 'Generated by BoardEase. Keep this invoice for your rental records.';

        return $this->render($lines);
    }

    public function receipt(Payment $payment): string
    {
        $invoice = $payment->invoice;
        $lease = $invoice?->lease;
        $lines = [
            'BOARDEASE PAYMENT RECEIPT',
            'Payment reference: '.($payment->reference_number ?: 'Recorded payment #'.$payment->id),
            'Transaction date: '.$payment->paid_at?->toDateTimeString(),
            'Transaction status: SUCCEEDED / RECORDED',
            'Payment method: '.$payment->method,
            'Amount received: PHP '.number_format((float) $payment->amount, 2),
            'Tenant: '.($lease?->tenant?->name ?? 'Tenant'),
            'Landlord: '.($lease?->landlord?->name ?? 'Landlord'),
            'Room: '.($lease?->room?->room_number ?? '—').' - '.($lease?->room?->title ?? 'Rental room'),
            'Invoice number: INV-'.str_pad((string) ($invoice?->id ?? ''), 6, '0', STR_PAD_LEFT).'  |  Billing period '.($invoice?->billing_period ?? ''),
            '',
            'INVOICE BREAKDOWN',
            'Monthly rent: PHP '.number_format((float) ($invoice?->base_rent ?? 0), 2),
        ];
        foreach ($invoice?->charges ?? [] as $charge) {
            $category = $charge->utility_type
                ? 'Utility - '.ucfirst($charge->utility_type)
                : 'Category - '.str_replace('_', ' ', (string) $charge->category);
            $lines[] = $category.' | '.($charge->description ?: 'Additional charge')
                .' | Period: '.($charge->billing_period ?: ($invoice?->billing_period ?? 'Not specified'))
                .' | PHP '.number_format((float) $charge->amount, 2);
        }
        $lines[] = 'Additional charges total: PHP '.number_format((float) ($invoice?->additional_charges_total ?? 0), 2);
        $lines[] = 'Invoice total: PHP '.number_format((float) ($invoice?->total_amount_due ?? 0), 2);
        $lines[] = 'Current invoice balance: PHP '.number_format((float) ($invoice?->remainingBalance() ?? 0), 2);
        $lines[] = '';
        $lines[] = 'This receipt is for a successfully recorded payment. Retain it with your rental records.';
        if (str_ends_with((string) $payment->method, '_simulated')) {
            $lines[] = 'Simulated payment record. No real money was processed.';
        }

        return $this->render($lines);
    }

    private function render(array $sourceLines): string
    {
        $lines = [];
        foreach ($sourceLines as $line) {
            $wrapped = wordwrap((string) $line, 88, "\n", true);
            array_push($lines, ...explode("\n", $wrapped));
        }
        $pages = array_chunk($lines, 46);
        $objects = [
            '<< /Type /Catalog /Pages 2 0 R >>',
            '<< /Type /Pages /Kids ['.implode(' ', array_map(fn ($index) => (4 + ($index * 2)).' 0 R', array_keys($pages))).'] /Count '.count($pages).' >>',
            '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
        ];
        foreach ($pages as $index => $pageLines) {
            $pageObject = 4 + ($index * 2);
            $contentObject = $pageObject + 1;
            $stream = "BT\n/F1 15 Tf\n50 790 Td\n(".$this->escape(array_shift($pageLines) ?? '').") Tj\n/F1 9 Tf\n";
            foreach ($pageLines as $line) {
                $stream .= "0 -15 Td\n(".$this->escape($line).") Tj\n";
            }
            $stream .= 'ET';
            $objects[] = '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 842] /Resources << /Font << /F1 3 0 R >> >> /Contents '.$contentObject.' 0 R >>';
            $objects[] = '<< /Length '.strlen($stream).">>\nstream\n{$stream}\nendstream";
        }

        $pdf = "%PDF-1.4\n";
        $offsets = [0];
        foreach ($objects as $index => $object) {
            $offsets[] = strlen($pdf);
            $pdf .= ($index + 1)." 0 obj\n{$object}\nendobj\n";
        }
        $xref = strlen($pdf);
        $pdf .= "xref\n0 ".(count($objects) + 1)."\n0000000000 65535 f \n";
        foreach (array_slice($offsets, 1) as $offset) {
            $pdf .= sprintf("%010d 00000 n \n", $offset);
        }
        $pdf .= 'trailer' . "\n<< /Size ".(count($objects) + 1)." /Root 1 0 R >>\nstartxref\n{$xref}\n%%EOF";

        return $pdf;
    }

    private function escape(string $text): string
    {
        $text = iconv('UTF-8', 'ASCII//TRANSLIT//IGNORE', $text) ?: '';
        return str_replace(['\\', '(', ')', "\r", "\n"], ['\\\\', '\\(', '\\)', ' ', ' '], $text);
    }
}
